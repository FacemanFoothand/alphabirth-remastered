function descriptions.push(id, desc)
    -- External Item Descriptions integration
    -- TODO: Should use their callback instead. Maybe both.
    if EID then
        for lang, loc in pairs(desc) do
            if lang ~= "synergy" then
                EID:addCollectible(id, loc[2], loc[1], lang)
                goto continue
            end
            for ID2, langTable in pairs(loc) do
                for syn_lang, texts in pairs(langTable) do
                    if EID["loaded_ab"] == nil then
                        EID:addSynergyCondition(id, ID2, texts.up, texts.down, syn_lang)
                    end
                end
            end
            ::continue::
        end
    end
end

return descriptions
